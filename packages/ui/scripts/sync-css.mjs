// Regenerates src/styles.ts from the .css files so Workers can inline the CSS
// as plain strings (no file loaders needed). Run after editing any .css file.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = (name) => fileURLToPath(new URL(`../src/${name}`, import.meta.url));
const tokens = readFileSync(src('tokens.css'), 'utf8');
const base = readFileSync(src('base.css'), 'utf8');

const out = `// GENERATED by scripts/sync-css.mjs from tokens.css and base.css. Do not edit.
export const tokensCss: string = ${JSON.stringify(tokens)};
export const baseCss: string = ${JSON.stringify(base)};
/** tokens + base, ready to inline in a <style> tag. */
export const allCss: string = tokensCss + '\\n' + baseCss;
`;
writeFileSync(src('styles.ts'), out);
console.log('wrote src/styles.ts');
